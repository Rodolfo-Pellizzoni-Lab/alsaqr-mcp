"""Custom accelerators in the accelerator socket (the cluster window, he-soc hardware/accel/).

accel_add        scaffold an accelerator (RTL from the template, unit test, C test) in a free slot and register it
accel_list       slots, bases, files
accel_unit_test  compile + run the accelerator alone in the generic unit testbench (seconds)
accel_soc_test   compile what changed into the SoC library, build the C test, run it on the SoC, wait for the verdict
accel_remove     unregister (files are kept)

The registry is hardware/accel/slots.json; accel_slots.sv and the managed block of hardware/Bender.yml are generated
from it, and work/compile.sh is regenerated (bender) whenever the block changes, so rtl_recompile and full
builds (hardware/xsim/build.sh) both see the accelerator sources.
"""
import json
import os
import re
import shutil
import subprocess
import time
import zlib
from pathlib import Path

from . import rtl, sim, soc, sources, status
from .config import Config, load

NUM_SLOTS = 8
WINDOW = 0x1000_0000
SLOT_SIZE = 0x1_0000
IRQ_ID = 9
_NAME_RE = re.compile(r"^[a-z][a-z0-9_]{1,30}$")
BEGIN, END = "  # accel: begin (managed by alsaqr-mcp; hardware/accel/slots.json)", "  # accel: end"


def _err(error, fix, **extra):
    d = {"error": error, "fix": fix}
    d.update(extra)
    return d


class _P:
    def __init__(self, cfg: Config):
        self.cfg = cfg
        self.hw = cfg.hardware
        self.dir = cfg.hardware / "accel"
        self.reg = self.dir / "slots.json"
        self.slots_sv = self.dir / "accel_slots.sv"
        self.socket_sv = self.dir / "accel_socket.sv"
        self.tmpl = self.dir / "templates"
        self.tb = self.dir / "tb" / "accel_tb.sv"
        self.sw = cfg.software / "accel"
        self.state = cfg.state / "accel"


def _load(p: _P) -> dict:
    try:
        return json.loads(p.reg.read_text())
    except (OSError, ValueError):
        return {"slots": {}}


def _save(p: _P, reg: dict):
    p.reg.write_text(json.dumps(reg, indent=1) + "\n")


def _base(slot: int) -> int:
    return WINDOW + slot * SLOT_SIZE


def _rtl_files(p: _P, name: str) -> list[Path]:
    """The accelerator's sources: every .sv/.v in hardware/accel/<name>/, packages (*_pkg.sv) first."""
    d = p.dir / name
    files = sorted(f for f in d.glob("*") if f.suffix in (".sv", ".v"))
    return sorted(files, key=lambda f: (not f.stem.endswith("_pkg"), f.name))


# ---------------------------------------------------------------- generated files
_PORTS = ("reg_we_i reg_addr_i reg_wdata_i reg_wstrb_i reg_user_i").split()


def _gen_slots(p: _P, reg: dict) -> str:
    used = {int(s): e for s, e in reg["slots"].items()}
    L = ["// GENERATED by alsaqr-mcp (accel_add / accel_remove) from hardware/accel/slots.json - do not edit.",
         "// One instance per occupied slot; an empty slot acknowledges at once with an error (DECERR at the bus).",
         "module accel_slots #(",
         "  parameter int unsigned NumSlots = 8",
         ") (",
         "  input  logic                                       clk_i,",
         "  input  logic                                       rst_ni,",
         "  input  logic                                       reg_req_i,",
         "  input  logic [(NumSlots > 1 ? $clog2(NumSlots) : 1)-1:0] reg_slot_i,",
         "  input  logic [15:0]                                reg_addr_i,",
         "  input  logic                                       reg_we_i,",
         "  input  logic [31:0]                                reg_wdata_i,",
         "  input  logic [3:0]                                 reg_wstrb_i,",
         "  input  logic [15:0]                                reg_user_i,",
         "  output logic                                       reg_ack_o,",
         "  output logic                                       reg_err_o,",
         "  output logic [31:0]                                reg_rdata_o,",
         "  output logic [NumSlots-1:0]                        mem_req_o,",
         "  input  logic [NumSlots-1:0]                        mem_gnt_i,",
         "  output logic [NumSlots-1:0]                        mem_we_o,",
         "  output logic [NumSlots-1:0][63:0]                  mem_addr_o,",
         "  output logic [NumSlots-1:0][63:0]                  mem_wdata_o,",
         "  output logic [NumSlots-1:0][7:0]                   mem_strb_o,",
         "  output logic [NumSlots-1:0][15:0]                  mem_user_o,",
         "  input  logic [NumSlots-1:0]                        mem_rvalid_i,",
         "  input  logic [63:0]                                mem_rdata_i,",
         "  input  logic [NumSlots-1:0]                        mem_err_i,",
         "  output logic [NumSlots-1:0]                        irq_o",
         ");",
         "  logic [NumSlots-1:0]       ack, present;",
         "  logic [NumSlots-1:0][31:0] rdata;",
         "",
         "  assign reg_ack_o   = ack[reg_slot_i];",
         "  assign reg_rdata_o = rdata[reg_slot_i];",
         "  assign reg_err_o   = !present[reg_slot_i];",
         ""]
    for s in range(NUM_SLOTS):
        e = used.get(s)
        if e:
            L += [f"  // slot {s}: {e['name']} (0x{_base(s):08x})",
                  f"  {e['module']} i_slot{s}_{e['name']} (",
                  "    .clk_i, .rst_ni,",
                  f"    .reg_req_i    ( reg_req_i && reg_slot_i == {s} ),",
                  *[f"    .{n:<12} ( {n} )," for n in _PORTS],
                  f"    .reg_ack_o    ( ack[{s}]          ),",
                  f"    .reg_rdata_o  ( rdata[{s}]        ),",
                  f"    .mem_req_o    ( mem_req_o[{s}]    ),",
                  f"    .mem_gnt_i    ( mem_gnt_i[{s}]    ),",
                  f"    .mem_we_o     ( mem_we_o[{s}]     ),",
                  f"    .mem_addr_o   ( mem_addr_o[{s}]   ),",
                  f"    .mem_wdata_o  ( mem_wdata_o[{s}]  ),",
                  f"    .mem_strb_o   ( mem_strb_o[{s}]   ),",
                  f"    .mem_user_o   ( mem_user_o[{s}]   ),",
                  f"    .mem_rvalid_i ( mem_rvalid_i[{s}] ),",
                  "    .mem_rdata_i  ( mem_rdata_i       ),",
                  f"    .mem_err_i    ( mem_err_i[{s}]    ),",
                  f"    .irq_o        ( irq_o[{s}]        )",
                  "  );",
                  f"  assign present[{s}] = 1'b1;", ""]
        else:
            L += [f"  // slot {s}: empty",
                  f"  assign ack[{s}] = reg_req_i && reg_slot_i == {s};",
                  f"  assign rdata[{s}] = 32'hdeadbeef;",
                  f"  assign present[{s}] = 1'b0;",
                  f"  assign mem_req_o[{s}] = 1'b0; assign mem_we_o[{s}] = 1'b0; assign mem_addr_o[{s}] = '0;",
                  f"  assign mem_wdata_o[{s}] = '0; assign mem_strb_o[{s}] = '0; assign mem_user_o[{s}] = '0; assign irq_o[{s}] = 1'b0;", ""]
    L += ["endmodule", ""]
    return "\n".join(L)


def _bender_block(p: _P, reg: dict) -> list[str]:
    files = []
    for s in sorted(reg["slots"], key=int):
        files += [sources.rel(p.cfg, f) for f in _rtl_files(p, reg["slots"][s]["name"])]
    files += ["accel/accel_slots.sv", "accel/accel_socket.sv"]
    return [BEGIN] + [f"  - {f}" for f in files] + [END]


def _sync(p: _P, reg: dict) -> dict:
    """Write accel_slots.sv and the Bender block from the registry; regenerate compile.sh if the block changed."""
    out = {}
    txt = _gen_slots(p, reg)
    if not p.slots_sv.exists() or p.slots_sv.read_text() != txt:
        p.slots_sv.write_text(txt)
        out["accel_slots"] = "regenerated"
    by = p.hw / "Bender.yml"
    lines = by.read_text().splitlines()
    block = _bender_block(p, reg)
    if BEGIN in lines:
        i, j = lines.index(BEGIN), lines.index(END)
        old = lines[i:j + 1]
        lines[i:j + 1] = block
    else:
        old = None
        k = lines.index("  - host/al_saqr.sv")
        lines[k:k] = block
    if old != block:
        by.write_text("\n".join(lines) + "\n")
        r = _regen_compile_sh(p.cfg)
        if r:
            return r
        out["compile_sh"] = "regenerated (Bender.yml accel block changed)"
    return out


def _regen_compile_sh(cfg: Config) -> dict | None:
    xs = cfg.hardware / "xsim"
    cmd = (f'source "{xs}/env.sh" >/dev/null && cd "$WORK" && (cd "$HW" && ./bender script vsim $BENDER_TARGETS) > vsim.tcl '
           f'&& python3 "$XSIM_DIR/vsim2xsim.py" vsim.tcl compile.sh "$HW" "$(echo $SOC_DEFINES $XSIM_DEFINES | tr " " ",")" '
           '&& chmod +x compile.sh')
    r = subprocess.run(["bash", "-c", cmd], capture_output=True, text=True, timeout=300,
                       env={**os.environ, "XSIM_WORK": str(cfg.work)})
    if r.returncode != 0:
        return _err("compile.sh regeneration failed", (r.stdout + r.stderr)[-600:])
    return None


# ---------------------------------------------------------------- accel_add
def _module_exists(cfg: Config, name: str) -> str | None:
    rx = re.compile(rf"^\s*module\s+{re.escape(name)}\b", re.M)
    for f in sources.compiled_files(cfg):
        try:
            if f.suffix in (".sv", ".v") and rx.search(f.read_text(errors="replace")):
                return sources.rel(cfg, f)
        except OSError:
            pass
    return None


def _subst(text: str, name: str, slot: int) -> str:
    ident = 0xAC00_0000 | (slot << 20) | (zlib.crc32(name.encode()) & 0xF_FFFF)
    return (text.replace("__NAME__", name).replace("__SLOT__", str(slot))
            .replace("__BASE__", f"0x{_base(slot):08X}").replace("__ID__", f"{ident:08X}"))


def accel_add(name: str, slot: int | None = None) -> dict:
    cfg = load()
    p = _P(cfg)
    if not p.socket_sv.exists():
        return _err("no accelerator socket", f"{p.socket_sv} is missing: this he-soc checkout predates the socket")
    if not _NAME_RE.match(name or ""):
        return _err("bad name", "lower-case identifier, 2-31 chars: [a-z][a-z0-9_]*")
    reg = _load(p)
    if any(e["name"] == name for e in reg["slots"].values()):
        return _err("already registered", f"{name} exists; accel_list shows it")
    clash = _module_exists(cfg, name)
    if clash:
        return _err("name taken", f"a module {name} already exists in {clash}; pick another name")
    free = [s for s in range(NUM_SLOTS) if str(s) not in reg["slots"]]
    if slot is None:
        if not free:
            return _err("no free slot", "accel_remove one first")
        slot = free[0]
    elif str(slot) in reg["slots"] or not 0 <= slot < NUM_SLOTS:
        return _err("slot not free", f"free slots: {free}")
    d, swd = p.dir / name, p.sw / name
    if d.exists() or swd.exists():
        return _err("directory exists", f"remove {d} / {swd} first or pick another name")
    d.mkdir(parents=True)
    swd.mkdir(parents=True)
    rtl_f, ut_f, c_f = d / f"{name}.sv", d / "accel_test.svh", swd / f"{name}.c"
    rtl_f.write_text(_subst((p.tmpl / "accel_template.sv").read_text(), name, slot))
    ut_f.write_text(_subst((p.tmpl / "accel_test.svh").read_text(), name, slot))
    (d / "accel_test_decls.svh").write_text((p.tmpl / "accel_test_decls.svh").read_text())
    c_f.write_text(_subst((p.tmpl / "accel_sw.c").read_text(), name, slot))
    (swd / "Makefile").write_text(f"APP := {name}\nXLEN:=64\n\ninclude $(shell pwd)/../common.mk\n")
    reg["slots"][str(slot)] = {"name": name, "module": name}
    _save(p, reg)
    s = _sync(p, reg)
    if "error" in s:
        return s
    return {"name": name, "slot": slot, "base": f"0x{_base(slot):08x}", "irq": f"PLIC ID {IRQ_ID} (shared)",
            "files": {"rtl": str(rtl_f), "unit_test": str(ut_f), "unit_test_decls": str(d / "accel_test_decls.svh"),
                      "sw_test": str(c_f)},
            "template": "working example: dst[i] = src[i] + ARG over LEN 64-bit words (registers documented in the rtl header)",
            "contract": str(p.dir / "README.md"),
            "next": [f"edit {rtl_f.name} (compute() or the FSM/registers), {ut_f.name} and {c_f.name}",
                     f"accel_unit_test(name='{name}')  ~5 s, no SoC",
                     f"accel_soc_test(name='{name}')  compile into the SoC + run the C test, ~6-8 min"]}


def accel_remove(name: str) -> dict:
    cfg = load()
    p = _P(cfg)
    reg = _load(p)
    hit = [s for s, e in reg["slots"].items() if e["name"] == name]
    if not hit:
        return _err("not registered", f"registered: {[e['name'] for e in reg['slots'].values()]}")
    del reg["slots"][hit[0]]
    _save(p, reg)
    s = _sync(p, reg)
    if "error" in s:
        return s
    return {"removed": name, "slot": int(hit[0]), "note": f"files kept in {p.dir / name} and {p.sw / name}; "
            "the next accel_soc_test or rtl_recompile of hardware/accel/accel_slots.sv takes it out of the SoC"}


def accel_list() -> dict:
    cfg = load()
    p = _P(cfg)
    reg = _load(p)
    slots = []
    for s in range(NUM_SLOTS):
        e = reg["slots"].get(str(s))
        if e:
            slots.append({"slot": s, "name": e["name"], "base": f"0x{_base(s):08x}",
                          "rtl": [sources.rel(cfg, f) for f in _rtl_files(p, e["name"])],
                          "sw_test": str(p.sw / e["name"])})
    return {"window": f"0x{WINDOW:08x}, {SLOT_SIZE // 1024} KB per slot, {NUM_SLOTS} slots", "irq": f"PLIC ID {IRQ_ID}",
            "accelerators": slots, "free": [s for s in range(NUM_SLOTS) if str(s) not in reg["slots"]]}


def _entry(p: _P, name: str):
    reg = _load(p)
    for s, e in reg["slots"].items():
        if e["name"] == name:
            return int(s), e, reg
    return None, None, reg


# ---------------------------------------------------------------- accel_unit_test
_XERR = re.compile(r"^ERROR: \[([^\]]+)\] (.*?)(?: \[([^\]]+?):(\d+)\])?\s*$")


def _xerrors(cfg: Config, text: str) -> list[dict]:
    out = []
    for l in text.splitlines():
        m = _XERR.match(l)
        if m:
            e = {"msg": m.group(2)[:200]}
            if m.group(3):
                e["file"], e["line"] = sources.rel(cfg, m.group(3)), int(m.group(4))
            out.append(e)
    return out


def accel_unit_test(name: str, seed: int = 1, waves: bool = False) -> dict:
    cfg = load()
    p = _P(cfg)
    slot, e, _ = _entry(p, name)
    if e is None:
        return _err("not registered", "accel_add it first (accel_list shows the registered ones)")
    files = _rtl_files(p, name)
    if not (p.dir / name / "accel_test.svh").exists():
        return _err("no unit test", f"write {p.dir / name / 'accel_test.svh'} (the body of the testbench's initial block)")
    decls = p.dir / name / "accel_test_decls.svh"
    if not decls.exists():
        decls.write_text("// module-scope declarations for accel_test.svh (functions, tasks, variables)\n")
    wd = p.state / name / "unit"
    if wd.exists():
        shutil.rmtree(wd)
    wd.mkdir(parents=True)
    # the SoC library is visible as `work`, so an accelerator can instantiate any IP the SoC compiles
    (wd / "xsim.ini").write_text(f"work={cfg.work / 'xsim.dir' / 'work'}\naccel_unit={wd / 'xsim.dir' / 'accel_unit'}\n")
    tb = p.tb
    inc = [f"-i {p.dir / name}"] + [f"-i {d}" for d in sources.include_dirs(cfg)]
    snap = f"unit_{name}"
    steps = [
        ("compile", f"xvlog -sv -work accel_unit -d ACCEL_DUT={e['module']} {' '.join(inc)} "
                    f"{' '.join(str(f) for f in files)} {tb}"),
        ("elaborate", f"xelab accel_unit.accel_tb -L accel_unit -L work -s {snap} -timescale 1ns/1ps -O0"
                      + (" -debug typical" if waves else "")),
    ]
    sim_cmd = f"xsim {snap} -sv_seed {int(seed)} "
    if waves:
        (wd / "waves.tcl").write_text("open_vcd waves.vcd\nlog_vcd [get_objects -r /accel_tb/dut/*]\nrun all\nclose_vcd\nquit\n")
        sim_cmd += "-tclbatch waves.tcl"
    else:
        sim_cmd += "-R"
    steps.append(("simulate", sim_cmd))
    t0 = time.time()
    log_all = []
    for step, cmd in steps:
        r = subprocess.run(["bash", "-c", f'source "{cfg.vivado_settings}" >/dev/null 2>&1 && {cmd}'], cwd=str(wd),
                           capture_output=True, text=True, timeout=1800)
        text = r.stdout + r.stderr
        (wd / f"{step}.log").write_text(text)
        log_all.append(text)
        errs = _xerrors(cfg, text)
        if step != "simulate" and (r.returncode != 0 or errs):
            return {"name": name, "result": f"{step}_error", "errors": errs[:12] or text.splitlines()[-8:],
                    "log": str(wd / f"{step}.log"), "wall_s": round(time.time() - t0, 1)}
    text = log_all[-1]
    verdict = next((l for l in text.splitlines() if l.startswith("ACCEL-UNIT ")), None)
    fails = [l.split("] ", 1)[1] for l in text.splitlines() if l.startswith("[ACCEL-UNIT] FAIL")]
    out = {"name": name, "result": "pass" if verdict and " PASS " in verdict else ("fail" if verdict else "no_verdict"),
           "summary": verdict, "wall_s": round(time.time() - t0, 1), "log": str(wd / "simulate.log")}
    # the test's own $display lines (simulator banner and verdict lines left out)
    body = text.split("run -all", 1)[-1].splitlines()
    own = [l for l in body if l.strip() and not l.startswith(("[ACCEL-UNIT]", "ACCEL-UNIT ", "$finish", "exit", "INFO:",
                                                                "Time:", "Time resolution"))]
    if own:
        out["output"] = own[-25:]
        if len(own) > 25:
            out["output_note"] = f"last 25 of {len(own)} lines; the rest is in log"
    if fails:
        out["failures"] = fails[:12]
    rt_err = [l for l in text.splitlines() if l.startswith(("ERROR", "FATAL", "Fatal"))]
    if rt_err:
        out["runtime_errors"] = rt_err[:6]
    if out["result"] != "pass":
        out["mem_log"] = str(wd / "accel_mem.log")
        out["hint"] = "accel_mem.log lists every memory access of the accelerator; waves=true dumps the dut's signals"
    if waves:
        out["vcd"] = str(wd / "waves.vcd")
    return out


# ---------------------------------------------------------------- accel_soc_test
def _soc_sources(p: _P, reg: dict) -> list[Path]:
    files = []
    for s in sorted(reg["slots"], key=int):
        files += _rtl_files(p, reg["slots"][s]["name"])
    return files + [p.slots_sv, p.socket_sv, p.hw / "host" / "al_saqr.sv"]


def accel_soc_test(name: str, wait_s: int = 900, extra_cflags: str | None = None) -> dict:
    cfg = load()
    p = _P(cfg)
    slot, e, reg = _entry(p, name)
    if e is None:
        return _err("not registered", "accel_add it first")
    fp = cfg.flow_problem()
    if fp:
        return fp
    out = {"name": name, "slot": slot}
    c = compile_changed(cfg)
    if c.get("recompiled"):
        out["recompiled"] = c["recompiled"]
    if "error" in c or c.get("errors"):
        out.update(result="compile_error", errors=c.get("errors") or c)
        return out
    # 2. the C test
    b = soc.sw_build(str(p.sw / name), extra_cflags=extra_cflags)
    if "error" in b:
        out.update(result="sw_build_error", build=b)
        return out
    # 3. simulate
    r = sim.sim_run(b["elf"], tag=f"accel_{name}")
    if "error" in r:
        out.update(result="sim_run_error", sim_run=r)
        return out
    out["run_id"] = r["run_id"]
    out["elab"] = r["elab"]
    if not wait_s:
        out["next"] = f"sim_status(run_id='{r['run_id']}', wait_s=900)"
        return out
    st = status.sim_status(r["run_id"], wait_s=min(int(wait_s), 900))
    return {**out, **_verdict(st)}


def compile_changed(cfg: Config) -> dict:
    """Sync the generated files, then compile the socket / accelerator sources edited since they went into the
    SoC library. {recompiled: [...], errors: [...]} (both may be empty)."""
    p = _P(cfg)
    if not p.socket_sv.exists():
        return {}
    reg = _load(p)
    s = _sync(p, reg)
    if "error" in s:
        return s
    recs, base = sources.compile_records(cfg), sources.baseline_ns(cfg)
    stale = [f for f in _soc_sources(p, reg) if sources.is_stale(cfg, f, recs, base)]
    if not stale:
        return {}
    rc = rtl.rtl_recompile([str(f) for f in stale])
    return {"recompiled": [c["file"] for c in rc["compiled"]], "errors": rc.get("errors", [])}


def _verdict(st: dict) -> dict:
    """Compact verdict of a finished (or still running) run."""
    v = {"state": st.get("state"), "sim_time_ns": st.get("sim_time_ns")}
    ex = st.get("exit") or {}
    if ex:
        v["verdict"] = ex.get("verdict")
        if ex.get("program_exit_code") is not None:
            v["exit_code"] = ex["program_exit_code"]
    con = st.get("console") or []
    # TEST / CHECK FAIL / TRAP lines, plus the last console lines (the program's own diagnostics)
    sel = [c for c in con if re.match(r"(TEST |CHECK FAIL|TRAP)", c.get("text", ""))] + con[-6:]
    seen, lines = set(), []
    for c in sorted(sel, key=lambda c: c.get("n", 0)):
        if c.get("n") not in seen:
            seen.add(c.get("n"))
            lines.append(f"{c['t_ns']}: {c['text']}")
    v["console"] = lines[-20:]
    if len(con) > len(lines):
        v["console_note"] = f"sim_uart(run_id=...) has all {st.get('uart_lines', len(con))} lines"
    if st.get("stall"):
        v["stall"] = st["stall"]
    if st.get("state") not in ("finished", "stalled", "timeout", "killed"):
        v["next"] = f"sim_status(run_id='{st.get('run_id')}', wait_s=900)"
    return v
